# Fail if any printed "(Nx)" is not competitor_time/our_time from the printed
# cells in that row, rounded with the same %.1f the table uses.
verify_speedups() {
    local file="$1"
    awk '
        function trim(s) {
            gsub(/^[ \t]+|[ \t]+$/, "", s);
            return s;
        }
        function to_ns(text,   n, a, v, u) {
            text = trim(text);
            n = split(text, a, " ");
            if (n < 2) {
                return -1;
            }
            v = a[1] + 0.0;
            u = a[2];
            if (u == "ns") return v;
            if (u == "us") return v * 1000.0;
            if (u == "ms") return v * 1000000.0;
            return -1;
        }
        function printed_ratio(text,   n, a, r) {
            text = trim(text);
            n = split(text, a, " ");
            if (n < 3) {
                return "";
            }
            r = a[3];
            gsub(/[()x]/, "", r);
            return r;
        }
        /^\| `/ {
            n = split($0, cells, "|");
            if (n < 6) {
                next;
            }
            label = trim(cells[2]);
            ours = trim(cells[3]);
            if (ours == "—" || ours == "") {
                ours_ns = -1;
            } else {
                ours_ns = to_ns(ours);
            }
            for (i = 4; i <= 6; i++) {
                cell = trim(cells[i]);
                if (cell == "" || cell == "—") {
                    continue;
                }
                their_ns = to_ns(cell);
                got = printed_ratio(cell);
                if (their_ns < 0 || got == "") {
                    printf "unparsed competitor cell %s in %s\n", cell, label > "/dev/stderr";
                    err = 1;
                    continue;
                }
                if (ours_ns <= 0) {
                    printf "speedup without our time in %s\n", label > "/dev/stderr";
                    err = 1;
                    continue;
                }
                expect = sprintf("%.1f", their_ns / ours_ns);
                if (expect != got) {
                    printf "ratio mismatch %s: printed %sx expected %sx from [%s] / [%s]\n", label, got, expect, cell, ours > "/dev/stderr";
                    err = 1;
                }
            }
        }
        END { exit err + 0; }
    ' "${file}"
}

replace_block() {
    local input="$1"
    local output="$2"
    local block_file="$3"
    awk -v start="${START_MARKER}" -v end="${END_MARKER}" -v block_file="${block_file}" '
        BEGIN {
            in_block = 0;
            seen_start = 0;
            seen_end = 0;
        }
        $0 == start {
            print;
            while ((getline line < block_file) > 0) {
                print line;
            }
            close(block_file);
            in_block = 1;
            seen_start = 1;
            next;
        }
        $0 == end {
            in_block = 0;
            seen_end = 1;
            print;
            next;
        }
        !in_block {
            print;
        }
        END {
            if (!seen_start || !seen_end) {
                print "Missing benchmark markers in README.md" > "/dev/stderr";
                exit 1;
            }
        }
    ' "${input}" > "${output}"
}

if [[ ! -f "${README_PATH}" ]]; then
    echo "README not found: ${README_PATH}" >&2
    exit 1
fi

block_tmp="$(mktemp)"
readme_tmp="$(mktemp)"
trap 'rm -f "${block_tmp}" "${readme_tmp}"' EXIT

generate_block > "${block_tmp}"
if ! verify_speedups "${block_tmp}"; then
    echo "Printed speedups do not match competitor_time / our_time." >&2
    exit 1
fi
replace_block "${README_PATH}" "${readme_tmp}" "${block_tmp}"

if [[ "${CHECK_MODE}" -eq 1 ]]; then
    if cmp -s "${README_PATH}" "${readme_tmp}"; then
        echo "README benchmark tables are up to date."
        exit 0
    fi
    echo "README benchmark tables are stale. Run: scripts/update_readme_bench.sh" >&2
    diff -u "${README_PATH}" "${readme_tmp}" || true
    exit 1
fi

mv "${readme_tmp}" "${README_PATH}"
echo "Updated README benchmark tables from target/criterion."
